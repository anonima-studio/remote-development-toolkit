#!/usr/bin/env bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
# Synthetic host profiles; tests never read the deployment profiles.
export REMOTE_DEV_PROFILE_DIR="$repo_root/tests/fixtures/host-profiles"
fixture=$(mktemp -d)
fake_bin=$fixture/bin
fake_home=$fixture/home
command_log=$fixture/commands.log
cleanup() {
  rm -rf -- "$fixture"
}
trap cleanup EXIT
mkdir -p "$fake_bin" "$fake_home/.ssh"

cat > "$fake_bin/uname" <<'EOF'
#!/usr/bin/env bash
printf 'Darwin\n'
EOF

cat > "$fake_bin/coder" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
printf 'coder %s\n' "$*" >> "$REMOTE_DEV_TEST_COMMAND_LOG"
if [[ " $* " == *' whoami '* ]]; then
  if [[ ${REMOTE_DEV_TEST_SIGNED_OUT:-false} == true ]]; then
    exit 1
  fi
  printf 'owner\n'
  exit 0
fi
if [[ " $* " == *' config-ssh '* ]]; then
  [[ " $* " == *' --disable-autostart '* && " $* " == *' --wait=no '* ]] || exit 1
  ssh_config=
  suffix=
  prefix=
  while (( $# > 0 )); do
    case "$1" in
      --ssh-config-file)
        ssh_config=$2
        shift 2
        ;;
      --hostname-suffix)
        suffix=$2
        shift 2
        ;;
      --ssh-host-prefix)
        prefix=$2
        shift 2
        ;;
      *) shift ;;
    esac
  done
  [[ -n $ssh_config && -n $suffix && -n $prefix ]]
  cat > "$ssh_config" <<CONFIG
# generated by synthetic coder
Host ${prefix}example-app
  ProxyCommand /synthetic/coder --global-config /synthetic/config ssh --stdio --disable-autostart --wait=no
CONFIG
  printf 'SSH config updated\n'
  exit 0
fi
printf 'unexpected synthetic coder command: %s\n' "$*" >&2
exit 1
EOF

cat > "$fake_bin/ssh" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
printf 'ssh %s\n' "$*" >> "$REMOTE_DEV_TEST_COMMAND_LOG"
if [[ " $* " == *' -G '* ]]; then
  printf 'hostname synthetic\n'
  exit 0
fi
cat <<'OUTPUT'
/usr/local/bin/codex
codex-cli 0.147.0
codex_path=/usr/local/bin/codex
codex_version=codex-cli 0.147.0
codex_auth=ready
project_dir=/home/coder/projects/example-app
worktree_root=/home/coder/projects/.codex-worktrees
worktree_root_state=ready
branch_sync_skill=/home/coder/.agents/skills/worktree-branch-sync
branch_sync_skill_state=ready
OUTPUT
EOF
chmod +x "$fake_bin/uname" "$fake_bin/coder" "$fake_bin/ssh"

cat > "$fake_home/.ssh/config" <<'EOF'
# existing config must survive
Include ~/.ssh/example-include.conf

Host *.coder
  ProxyCommand existing-proxy
EOF
chmod 0600 "$fake_home/.ssh/config"

run_setup() {
  env \
    HOME="$fake_home" \
    PATH="$fake_bin:$PATH" \
    REMOTE_DEV_TEST_COMMAND_LOG="$command_log" \
    "$repo_root/bin/remote-dev" --profile example-profile \
    codex-desktop example-app --project-dir example-app
}

setup_output=$(run_setup)
for expected in \
  'READY    Codex Desktop SSH connection is configured on this Mac.' \
  'Host     example-profile.example-app' \
  'Folder   /home/coder/projects/example-app' \
  'Worktrees /home/coder/projects/.codex-worktrees' \
  'Version  codex-cli 0.147.0' \
  'Settings -> Worktrees -> Worktree root' \
  'worktree-vars example-app' \
  'git -C /home/coder/projects/example-app worktree list --porcelain' \
  'preview example-app <port>' \
  'Settings -> Connections -> SSH -> Add'; do
  if [[ $setup_output != *"$expected"* ]]; then
    printf 'desktop setup output omitted %q:\n%s\n' "$expected" "$setup_output" >&2
    exit 1
  fi
done

ssh_fragment=$fake_home/.ssh/remote-dev-example-profile.conf
grep -Fxq 'Host example-profile.example-app' "$ssh_fragment"
grep -Fxq '  ProxyCommand /synthetic/coder --no-version-warning --global-config /synthetic/config ssh --stdio --disable-autostart --wait=no' \
  "$ssh_fragment"
expected_include="Include \"$ssh_fragment\""
grep -Fxq "$expected_include" \
  "$fake_home/.ssh/config"
grep -Fxq '  ProxyCommand existing-proxy' "$fake_home/.ssh/config"
include_line=$(grep -Fn -m1 "$expected_include" \
  "$fake_home/.ssh/config" | cut -d: -f1)
host_line=$(grep -n -m1 '^Host \*\.coder$' "$fake_home/.ssh/config" | cut -d: -f1)
if (( include_line >= host_line )); then
  echo 'Remote Dev SSH fragment is not included before existing Host blocks' >&2
  exit 1
fi

expected_config="$fake_home/Library/Application Support/remote-dev/coder/example-profile"
if [[ $(<"$expected_config/url") != https://coder.example.invalid ]]; then
  echo 'desktop setup did not persist the profile URL for SSH ProxyCommand' >&2
  exit 1
fi
if ! grep -Fq -- "--global-config $expected_config" "$command_log"; then
  echo 'desktop setup did not isolate the Coder profile under Remote Dev ownership' >&2
  exit 1
fi
if ! grep -Fq -- '--no-version-warning' "$command_log"; then
  echo 'desktop setup did not suppress compatible Coder client/server version noise' >&2
  exit 1
fi
if grep -Fq coderv2 "$command_log"; then
  echo 'desktop setup leaked Coder internal directory naming to its contract' >&2
  exit 1
fi
if ! grep -Fq -- '--no-wildcard --ssh-host-prefix example-profile. --hostname-suffix example-profile.coder' \
  "$command_log"; then
  echo 'desktop setup did not request discoverable profile-specific SSH aliases' >&2
  exit 1
fi

run_setup >/dev/null
if [[ $(grep -Fxc "$expected_include" \
  "$fake_home/.ssh/config") != 1 ]]; then
  echo 'desktop setup duplicated its SSH Include on the second run' >&2
  exit 1
fi

set +e
invalid_output=$(env \
  HOME="$fake_home" \
  PATH="$fake_bin:$PATH" \
  REMOTE_DEV_TEST_COMMAND_LOG="$command_log" \
  "$repo_root/bin/remote-dev" --profile example-profile \
  codex-desktop example-app --project-dir ../example-app 2>&1)
invalid_status=$?
set -e
if (( invalid_status != 2 )) || \
   [[ $invalid_output != *'project directory must not contain dot components'* ]]; then
  printf 'unsafe desktop project directory was not rejected: %s\n' \
    "$invalid_output" >&2
  exit 1
fi

signed_out_home=$fixture/signed-out-home
mkdir -p "$signed_out_home"
set +e
signed_out_output=$(env \
  HOME="$signed_out_home" \
  PATH="$fake_bin:$PATH" \
  REMOTE_DEV_TEST_COMMAND_LOG="$command_log" \
  REMOTE_DEV_TEST_SIGNED_OUT=true \
  "$repo_root/bin/remote-dev" --profile example-profile \
  codex-desktop example-app 2>&1)
signed_out_status=$?
set -e
if (( signed_out_status != 1 )) || \
   [[ $signed_out_output != *'Run this command from an interactive Terminal on the Mac'* ]]; then
  printf 'non-interactive Coder login did not produce actionable recovery: %s\n' \
    "$signed_out_output" >&2
  exit 1
fi

printf 'PASS     Codex Desktop Coder SSH setup is packaged and idempotent\n'
